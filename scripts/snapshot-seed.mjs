// Freeze the CURRENT database into supabase/seed.sql.
// After you've cleaned up the live site and added the posts, bets and events you want,
// run this once; from then on, running seed.sql in Supabase brings back exactly this state.
//
//   node --env-file=.env.local scripts/snapshot-seed.mjs
//
// Needs NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in .env.local (reads every row, bypassing RLS).
// Logins (auth users) are NOT in the snapshot and are never touched by seed.sql: profiles keep their ids,
// so everyone's login stays linked to their profile. Photos in Storage aren't copied either (only their links).

import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

// Parents before children (so the links between tables are valid when inserting)
export const TABLES = [
  "profiles",
  "places",
  "skills",
  "visits",
  "events",
  "posts",
  "post_reactions",
  "post_comments",
  "anonymous_posts",
  "endorsements",
  "connections",
  "rsvps",
  "event_reviews",
  "worst_classes",
  "profile_views",
  "odds_lines",
  "odds_votes",
];

// One INSERT per table, rows as JSON (handles quotes, emoji, newlines, nulls, dates safely)
export function buildSeed(dataByTable, takenAt = new Date().toISOString()) {
  const tag = "$snapshot$";
  const lines = [
    "-- =========================================================",
    `-- LOCKEDOUT SEED (snapshot of the live database, ${takenAt})`,
    "-- Generated by scripts/snapshot-seed.mjs. Don't edit by hand: change the site, then re-run the script.",
    "-- Running this WIPES all app data and restores this snapshot. Logins (auth) are not touched.",
    "-- =========================================================",
    "",
    "begin;",
    "",
    `truncate ${TABLES.join(", ")} cascade;`,
    "",
  ];
  for (const table of TABLES) {
    const rows = dataByTable[table] ?? [];
    lines.push(`-- ${table}: ${rows.length} rows`);
    if (rows.length === 0) {
      lines.push("");
      continue;
    }
    const json = JSON.stringify(rows);
    if (json.includes(tag)) throw new Error(`${table} contains ${tag}; pick another quote tag`);
    lines.push(`insert into ${table} select * from json_populate_recordset(null::${table}, ${tag}${json}${tag});`, "");
  }
  lines.push("commit;", "");
  return lines.join("\n");
}

async function main() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local");
    process.exit(1);
  }
  const db = createClient(url, key, { auth: { persistSession: false } });

  const data = {};
  for (const table of TABLES) {
    const rows = [];
    for (let from = 0; ; from += 1000) {
      const { data: page, error } = await db.from(table).select("*").range(from, from + 999);
      if (error) {
        console.error(`✗ ${table}: ${error.message}`);
        process.exit(1);
      }
      rows.push(...page);
      if (page.length < 1000) break;
    }
    data[table] = rows;
    console.log(`✓ ${table.padEnd(16)} ${rows.length} rows`);
  }

  const out = new URL("../supabase/seed.sql", import.meta.url);
  writeFileSync(out, buildSeed(data));
  console.log("\nWrote supabase/seed.sql. Check it in a PR (git diff), then commit.");
}

// run only when executed directly (the test imports buildSeed)
if (import.meta.url === `file://${process.argv[1]}`) main();
